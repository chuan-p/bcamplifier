#!/usr/bin/env node

import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, "..");
const srcDir = path.join(rootDir, "src");
const distDir = path.join(rootDir, "dist");

const metaPath = path.join(srcDir, "userscript.meta.js");
const entryPath = path.join(srcDir, "index.js");
const playerStylesPath = path.join(srcDir, "styles", "player.css");
const enhancementStylesPath = path.join(srcDir, "styles", "enhancements.css");
const hostErrorsPath = path.join(srcDir, "utils", "host-errors.js");

const rootOutputPath = path.join(rootDir, "bcamplifier.user.js");
const distOutputPath = path.join(distDir, "bcamplifier.user.js");
const extensionHostErrorsPath = path.join(rootDir, "extension.host-errors.js");

const [meta, playerStyles, enhancementStyles] = await Promise.all([
    readFile(metaPath, "utf8"),
    readFile(playerStylesPath, "utf8"),
    readFile(enhancementStylesPath, "utf8"),
]);

validateUserscriptMeta(meta);
if (!playerStyles.trim() || !enhancementStyles.trim()) {
    throw new Error("Stylesheets in src/styles/ must not be empty.");
}

const scriptVersion = getUserscriptVersion(meta);
const buildId = await computeSourceBuildId(srcDir);

const userscriptResult = await esbuild.build({
    entryPoints: [entryPath],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: ["es2020"],
    minify: true,
    legalComments: "none",
    banner: { js: meta.trimEnd() },
    define: {
        __BCAMPX_PLAYER_SHELL_CSS__: JSON.stringify(minifyCss(playerStyles)),
        __BCAMPX_ENHANCEMENT_CSS__: JSON.stringify(minifyCss(enhancementStyles)),
        __BCAMPX_SCRIPT_VERSION__: JSON.stringify(scriptVersion),
        __BCAMPX_BUILD_ID__: JSON.stringify(buildId),
    },
});

const userscriptCode = userscriptResult.outputFiles[0].text;

// The extension runs the same host error mapping outside the userscript bundle,
// so build a small global helper from the exact same ES module.
const hostErrorsResult = await esbuild.build({
    stdin: {
        contents: `import { describeHostError } from ${JSON.stringify(hostErrorsPath)};
globalThis.__BCAMPX_HOST_ERRORS__ = { describeHostError };`,
        resolveDir: rootDir,
    },
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: ["es2020"],
    minify: false,
    banner: {
        js: [
            '"use strict";',
            "// Generated from src/utils/host-errors.js by scripts/build-userscript.mjs.",
            "// Do not edit this file: edit the source module and rebuild.",
        ].join("\n"),
    },
});

const extensionHostErrorsCode = hostErrorsResult.outputFiles[0].text;

await mkdir(distDir, { recursive: true });
await Promise.all([
    writeFile(rootOutputPath, userscriptCode, "utf8"),
    writeFile(distOutputPath, userscriptCode, "utf8"),
    writeFile(extensionHostErrorsPath, extensionHostErrorsCode, "utf8"),
]);

console.log(`Built userscript: ${rootOutputPath}`);
console.log(`Built userscript: ${distOutputPath}`);
console.log(`Built extension helper: ${extensionHostErrorsPath}`);

function validateUserscriptMeta(value) {
    const trimmed = value.trim();
    if (!trimmed.startsWith("// ==UserScript==")) {
        throw new Error("Userscript metadata must start with // ==UserScript==.");
    }
    if (!trimmed.endsWith("// ==/UserScript==")) {
        throw new Error("Userscript metadata must end with // ==/UserScript==.");
    }
}

function getUserscriptVersion(value) {
    const match = value.match(/^\/\/\s+@version\s+(.+)$/m);
    if (!match || !match[1].trim()) {
        throw new Error("Userscript metadata must include @version.");
    }
    return match[1].trim();
}

function minifyCss(css) {
    return css
        .replace(/\/\*[\s\S]*?\*\//g, "")
        .split("\n")
        .map((line) => line.trim())
        .filter(Boolean)
        .join(" ");
}

async function listFilesSorted(dir) {
    const entries = (await readdir(dir)).sort();
    const files = [];
    for (const entry of entries) {
        const fullPath = path.join(dir, entry);
        const info = await stat(fullPath);
        if (info.isDirectory()) {
            files.push(...(await listFilesSorted(fullPath)));
        } else {
            files.push(fullPath);
        }
    }
    return files;
}

async function computeSourceBuildId(dir) {
    const hash = createHash("sha256");
    const files = await listFilesSorted(dir);
    for (const file of files) {
        hash.update(path.relative(rootDir, file));
        hash.update("\0");
        hash.update(await readFile(file, "utf8"));
        hash.update("\0");
    }
    return hash.digest("hex").slice(0, 12);
}
